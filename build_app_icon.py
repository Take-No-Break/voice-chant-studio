"""Build the original microphone/spark mark at Windows and WoW icon sizes."""
from pathlib import Path
from PIL import Image,ImageDraw
BASE=Path(__file__).resolve().parent
def main():
    folder=BASE/'assets/branding';folder.mkdir(parents=True,exist_ok=True)
    scale=4
    image=Image.new('RGBA',(256*scale,256*scale),(0,0,0,0));draw=ImageDraw.Draw(image)
    def box(values):return tuple(round(v*scale) for v in values)
    navy='#132d3a';teal='#65d5c3';white='#f4faf7';gold='#f2c36b'
    draw.rounded_rectangle(box((5,5,251,251)),radius=54*scale,fill=navy)
    draw.rounded_rectangle(box((77,43,151,148)),radius=37*scale,fill=white)
    draw.arc(box((56,87,172,180)),0,180,fill=teal,width=12*scale)
    draw.line(box((56,104,56,133)),fill=teal,width=12*scale)
    draw.line(box((172,104,172,133)),fill=teal,width=12*scale)
    draw.line(box((114,180,114,207)),fill=teal,width=12*scale)
    draw.rounded_rectangle(box((83,204,145,216)),radius=6*scale,fill=teal)
    draw.polygon([box(p) for p in [(195,41),(201,59),(219,65),(201,71),(195,89),(189,71),(171,65),(189,59)]],fill=gold)
    icon=image.resize((256,256),Image.Resampling.LANCZOS)
    icon.save(folder/'app-icon.png')
    icon.save(folder/'app-icon.ico',sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
    icon.resize((64,64),Image.Resampling.LANCZOS).save(BASE/'addon/Icon.tga',compression=None)
    (folder/'app-icon.svg').write_text('''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><rect x="5" y="5" width="246" height="246" rx="54" fill="#132d3a"/><rect x="77" y="43" width="74" height="105" rx="37" fill="#f4faf7"/><path d="M56 104v22a58 47 0 0 0 116 0v-22M114 180v30M89 210h50" fill="none" stroke="#65d5c3" stroke-width="12" stroke-linecap="round"/><path d="m195 41 6 18 18 6-18 6-6 18-6-18-18-6 18-6z" fill="#f2c36b"/></svg>''',encoding='utf8')
    (folder/'README.md').write_text('# Voice Chant Studio mark\n\nOriginal microphone and four-point spark design created for this project. Navy background, white microphone, teal stand and gold spark. The ICO, PNG and WoW TGA are generated by build_app_icon.py; the SVG is the editable vector reference. Pillow is a build-time dependency only.\n',encoding='utf8')
    print('Built PNG, multi-size ICO, 64x64 RGBA TGA and SVG reference')
if __name__=='__main__':main()
